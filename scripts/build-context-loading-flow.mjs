import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {layoutFlowGraph} from '../report/flow.mjs';

// Explicit explanatory relationships, not inferred execution events. Reuse the
// report's routing and label placement without inventing evidence references.
export function contextLoadingLayouts(){
  const definitions={
    initial:{
      nodes:[
        ['preset',0,'当前预设','Standard · 启动配置','result'],
        ['capabilities',1,'接口与 Skill 目录','工具定义 · Skill 目录\n名称、用途与参数\n已装填：3,240 tokens'],
        ['rules',1,'系统与适用指令','系统基底 · AGENTS.md\n按当前工作目录发现\n已装填：2,880 tokens'],
        ['assembly',2,'补齐环境与任务','环境信息 · 用户输入\n仅加入本次适用内容\n本层：560 tokens'],
        ['request',3,'首次模型请求','6 个内容层 · 15 项\n≈ 6,680 tokens\nSkill 正文尚未读取','result']
      ],
      edges:[['preset','capabilities','提供接口'],['preset','rules','提供规则'],['capabilities','assembly','加入接口与目录'],['rules','assembly','加入适用规则'],['assembly','request','汇合为请求']]
    },
    skill:{
      nodes:[
        ['current',0,'当前请求','≈ 6,680 tokens\n已包含 Skill 目录','result'],
        ['catalog',1,'发现适用方法','trace-analysis\n目录描述：180 tokens\n已含在原请求中'],
        ['retained',1,'保留已有内容','系统、工具、指令与任务\n≈ 6,680 tokens\n不重复计算目录'],
        ['body',2,'读取 Skill 正文','按需读取 trace-analysis\n正文：2,840 tokens\n读取后追加到上下文'],
        ['request',3,'下一次模型请求','保留内容 + 新增正文\n≈ 9,520 tokens\n目录不重复加入','result']
      ],
      edges:[['current','catalog','选择适用方法'],['current','retained','保留'],['catalog','body','读取正文'],['retained','request','沿用原内容'],['body','request','追加正文']]
    },
    conditional:{
      nodes:[
        ['current',0,'当前请求','≈ 6,680 tokens\n已包含当前适用指令','result'],
        ['condition',1,'访问更深目录？','','decision'],
        ['extra',2,'补充目录指令','子目录 AGENTS.md\n新增：420 tokens\n仅适用于对应路径'],
        ['unchanged',2,'沿用当前指令','未触发新的目录条件\n不追加子目录指令\n≈ 6,680 tokens'],
        ['request',3,'下一次模型请求','保留原有内容\n≈ 7,100 tokens\n补充内容来自触发结果','result']
      ],
      edges:[['current','condition','核对适用范围'],['condition','extra','是 · 发现新指令'],['condition','unchanged','否 · 继续当前范围'],['extra','request','追加适用内容'],['unchanged','request','沿用']]
    }
  };
  return Object.fromEntries(Object.entries(definitions).map(([id,definition])=>{
    const nodes=definition.nodes.map(([id,rank,label,detail,kind='action'],index)=>({id,rank,label,detail,kind,index,basis:'recorded',incoming:[],outgoing:[]}));
    const byId=new Map(nodes.map(node=>[node.id,node]));
    const edges=definition.edges.map(([from,to,label],index)=>({from,to,label,index,kind:'dependency'}));
    for(const edge of edges){byId.get(edge.from).outgoing.push(edge);byId.get(edge.to).incoming.push(edge);}
    return [id,Object.fromEntries(['horizontal','vertical'].map(orientation=>{
      const layout=layoutFlowGraph({nodes,edges,orientation});
      return [orientation,{width:layout.width,height:layout.height,orientation,
        nodes:layout.nodes.map(({id,x,y,width,height,kind,label,titleLines,detailLines})=>({id,x,y,width,height,kind,label,titleLines,detailLines})),
        edges:layout.links.map(({from,to,path,end,labelLines,labelBox,labelWidth,labelHeight,labelX,labelY})=>({from,to,path,end,labelLines,labelBox,labelWidth,labelHeight,labelX,labelY}))}];
    }))];
  }));
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const layouts=contextLoadingLayouts(),target=new URL('../docs/demo/context-loading/flow-layouts.js',import.meta.url);
  await writeFile(target,'// Generated by scripts/build-context-loading-flow.mjs using report/flow.mjs.\nwindow.CONTEXT_LOADING_LAYOUTS = '+JSON.stringify(layouts)+';\n');
  console.log('Built three flow studies using the report layout.');
}
